/** Words in args/*.rs that are not commands or flags: values, and errors' words. */
const NOT_COMMANDS = new Set(['origin', 'message', 'json', 'public', 'private', 'approve', 'reject', 'old', 'new', 'owner', 'member', 'read', 'write', 'expected']);
const HOOKS = /^(claude|opencode)-/;

/** The commands, subcommands and flags `args/*.rs` parses. */
export function parsedWords(root) {
  const dir = join(root, 'backend/crates/yoneda-cli/src/args');
  const words = new Set();
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.rs') && f !== 'docs.rs' && f !== 'parser.rs')) {
    const code = readFileSync(join(dir, file), 'utf8').split('#[cfg(test)]\n').find((part) => part.includes('fn '));
    for (const line of code.split('\n')) {
      if (/usage\(|exactly\(|format!|^\s*\/\//.test(line)) continue;
      for (const [, word] of line.matchAll(/"([a-z][a-z0-9-]*)"/g)) words.add(word);
    }
  }
  return [...words].filter((word) => !NOT_COMMANDS.has(word)).sort();
}

/** Words the code parses that no row of the table names. */
export function coverageGaps(root) {
  const table = TABLE.join(' ');
  return parsedWords(root).filter((word) => !new RegExp(`(^|[^a-z-])(--)?${word}($|[^a-z-])`).test(table) && !(HOOKS.test(word) && table.includes(`hook ${word}`)));
}

/** The table as text: status, row, milliseconds, what it found. */
export function printable(rows) {
  const wide = Math.max(...rows.map((r) => r.row.length));
  const lines = rows.map((r) => `${r.status.padEnd(7)} ${r.row.padEnd(wide)} ${String(r.ms).padStart(6)} ms  ${r.note ?? ''}`);
  return lines.join('\n');
}
