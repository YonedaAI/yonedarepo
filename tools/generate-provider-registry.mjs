#!/usr/bin/env node
// Deterministic public catalog export. No credentials or provider I/O.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
const source = new URL('../backend/crates/yoneda-core/src/providers.json', import.meta.url);
const target = new URL('../shared/provider-registry.ts', import.meta.url);
const registry = JSON.parse(readFileSync(source, 'utf8'));
const ids = new Set();
for (const provider of registry) {
  if (ids.has(provider.id) || !provider.models.some(model => model.id === provider.default_model))
    throw new Error('Invalid provider catalog identity or default');
  ids.add(provider.id);
}
const raw = `// Generated by node tools/generate-provider-registry.mjs; edit the Rust manifest.\nexport const providerRegistry = ${JSON.stringify(registry, null, 2)};\n`;
const output = execFileSync('pnpm', ['exec', 'biome', 'format', '--stdin-file-path', 'shared/provider-registry.ts'], { input: raw, encoding: 'utf8' });
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Provider registry needs regeneration');
} else writeFileSync(target, output);
