//! Fetch-only API placements. Storage authorities, workflows and resource names stay put.
use super::spec::{Spec, WorkerSpec};
use crate::process::Result;
use serde::{Deserialize, Serialize};
use serde_json::json;
use std::collections::BTreeSet;

const CODES: [&str; 6] = ["enam", "weur", "apac", "oc", "sam", "afr"];

#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct ApiRegion {
    pub code: String,
    pub placement: String,
}

fn validate(regions: &[ApiRegion]) -> Result<()> {
    let mut seen = BTreeSet::new();
    for region in regions {
        if !CODES.contains(&region.code.as_str()) || !seen.insert(region.code.clone()) {
            return Err(format!("Unknown or duplicate API region {}", region.code).into());
        }
        let Some((provider, code)) = region.placement.split_once(':') else {
            return Err("An API placement needs a cloud provider and region".into());
        };
        if !["aws", "gcp", "azure"].contains(&provider)
            || code.is_empty()
            || !code.bytes().all(|c| c.is_ascii_alphanumeric() || c == b'-')
        {
            return Err(format!("Invalid API placement {}", region.placement).into());
        }
    }
    if !regions.iter().any(|r| r.code == "enam") {
        return Err("API regions require the non-dispatching enam authority adapter".into());
    }
    Ok(())
}

fn alias(platform: &WorkerSpec, env: &str, region: &ApiRegion) -> WorkerSpec {
    let mut worker = platform.clone();
    worker.role = format!("api-{}", region.code);
    worker.file = format!("wrangler.{env}-{}.jsonc", worker.role);
    worker.notes = vec![
        format!(
            "Fetch-only {} API placement; all authorities stay in the primary platform Worker.",
            region.code
        ),
        "Generated by xtask/src/infra/api_regions.rs; change api_regions in the environment spec."
            .into(),
    ];
    worker.ephemeral = false;
    worker.always_on.clear();
    let c = &mut worker.config;
    c["name"] = json!(format!("{{prefix}}-{}", worker.role));
    c["workers_dev"] = json!(true);
    c["placement"] = json!({"mode":"targeted","region":region.placement});
    c["vars"]["CELL"] = json!("enam");
    c["vars"]["API_REGION"] = json!(region.code);
    for binding in c["durable_objects"]["bindings"]
        .as_array_mut()
        .into_iter()
        .flatten()
    {
        binding["script_name"] = json!("{prefix}-platform");
    }
    for binding in c["workflows"].as_array_mut().into_iter().flatten() {
        binding["script_name"] = json!("{prefix}-platform");
        if let Some(binding) = binding.as_object_mut() {
            for key in ["limits", "concurrency", "schedules", "default_retention"] {
                binding.remove(key);
            }
        }
    }
    if let Some(queues) = c["queues"].as_object_mut() {
        queues.remove("consumers");
    }
    if let Some(config) = c.as_object_mut() {
        for key in [
            "migrations",
            "containers",
            "routes",
            "triggers",
            "exports",
            "assets",
        ] {
            config.remove(key);
        }
    }
    worker
}

fn bind(worker: &mut WorkerSpec, regions: &[ApiRegion]) -> Result<()> {
    let services = worker.config["services"]
        .as_array_mut()
        .ok_or_else(|| format!("{} has no service bindings", worker.role))?;
    for region in regions {
        let binding = format!("API_{}", region.code.to_uppercase());
        if services.iter().any(|s| s["binding"] == binding) {
            return Err(format!("{} already binds {binding}", worker.role).into());
        }
        services
            .push(json!({"binding":binding,"service":format!("{{prefix}}-api-{}",region.code)}));
    }
    Ok(())
}

fn authority_binding(worker: &mut WorkerSpec) -> Result<()> {
    let services = worker.config["services"]
        .as_array_mut()
        .ok_or("An API participant needs service bindings")?;
    let target = json!({"binding":"CELL_ENAM","service":"{prefix}-api-enam"});
    if let Some(existing) = services.iter_mut().find(|s| s["binding"] == "CELL_ENAM") {
        *existing = target;
    } else {
        services.push(target);
    }
    Ok(())
}

pub(super) fn expand(spec: &mut Spec) -> Result<()> {
    if spec.api_regions.is_empty() {
        return Ok(());
    }
    validate(&spec.api_regions)?;
    let platform = spec
        .workers
        .iter()
        .find(|w| w.role == "platform")
        .ok_or("API regions require the primary platform Worker")?
        .clone();
    let aliases: Vec<_> = spec
        .api_regions
        .iter()
        .map(|r| alias(&platform, &spec.env, r))
        .collect();
    let at = spec
        .workers
        .iter()
        .rposition(|w| w.role == "platform" || w.role.starts_with("platform-"))
        .ok_or("API regions have no provider")?
        + 1;
    spec.workers.splice(at..at, aliases);
    for worker in &mut spec.workers {
        if matches!(
            worker.role.as_str(),
            "platform" | "platform-weur" | "agents" | "edge"
        ) || worker.role.starts_with("api-")
        {
            authority_binding(worker)?;
        }
        match worker.role.as_str() {
            "platform" | "agents" | "edge" => {
                worker
                    .config
                    .as_object_mut()
                    .ok_or("Worker config must be an object")?
                    .remove("placement");
                bind(worker, &spec.api_regions)?;
            }
            "platform-weur" => {
                worker.config["vars"]["API_REGION"] = json!("weur");
            }
            _ => {}
        }
    }
    Ok(())
}
