//! The 300-line rule (AGENTS.md): a source module over 300 nonblank lines fails, unless it's in
//! `xtask/line-limits.toml`, a list of the files that broke the rule when it began to be
//! enforced. The list can only shrink: a listed file can't grow, a file that drops under the
//! limit leaves the list, and against `--base` no entry may appear or rise. Tests (inline test
//! modules too) and generated contracts aren't gated; the report counts them.
use super::{base, file_at};
use crate::process::Result;
use serde::Deserialize;
use std::collections::BTreeMap;
use std::path::Path;
use std::process::Command;

pub(super) const LIMIT: usize = 300;
const TABLE: &str = "xtask/line-limits.toml";
const EXTENSIONS: [&str; 6] = ["rs", "ts", "tsx", "js", "mjs", "cjs"];
const GENERATED: &str = "// Generated by `cargo xtask contracts`";
const HEADER: &str =
    "# Source files over the 300-line rule, with their nonblank lines, excluding inline test
# modules (xtask/src/health/lines.rs). This list only shrinks: split a file, then run
# `cargo xtask health lines --update`. Never add an entry or raise a count.
[files]
";

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Table {
    files: BTreeMap<String, usize>,
}

/// What the rule sees in a tree.
pub(super) struct Census {
    pub over: BTreeMap<String, usize>,
    pub tests_over: usize,
    pub generated_over: usize,
}

fn parse(source: &str) -> Result<BTreeMap<String, usize>> {
    let table: Table = toml::from_str(source).map_err(|error| format!("{TABLE}: {error}"))?;
    Ok(table.files)
}

pub(super) fn listed(root: &Path) -> Result<BTreeMap<String, usize>> {
    parse(&std::fs::read_to_string(root.join(TABLE))?)
}

fn is_test(path: &str) -> bool {
    let name = path.rsplit('/').next().unwrap_or(path);
    path.starts_with("tests/")
        || path.contains("/tests/")
        || name == "tests.rs"
        || name.ends_with("_tests.rs")
        || name.contains(".test.")
}

fn is_generated(path: &str, text: &str) -> bool {
    path.starts_with("shared/contracts/") && text.starts_with(GENERATED)
}

/// Nonblank lines outside inline `#[cfg(test)] mod name { .. }` blocks, whose closing brace
/// rustfmt puts at the attribute's indentation. `mod tests;` is a line like any other.
pub(super) fn code_lines(text: &str) -> usize {
    let mut lines = text.lines().peekable();
    let mut count = 0;
    while let Some(line) = lines.next() {
        let opens_module = |next: &&str| {
            let next = next.trim();
            next.ends_with('{') && (next.starts_with("mod ") || next.starts_with("pub mod "))
        };
        if line.trim() == "#[cfg(test)]" && lines.peek().is_some_and(opens_module) {
            let indent = line.len() - line.trim_start().len();
            let close = format!("{}}}", " ".repeat(indent));
            lines.by_ref().find(|inner| *inner == close);
        } else if !line.trim().is_empty() {
            count += 1;
        }
    }
    count
}

/// Every tracked or new file under `root`, ignored files aside.
fn files(root: &Path) -> Result<Vec<String>> {
    let output = Command::new("git")
        .current_dir(root)
        .args(["ls-files", "--cached", "--others", "--exclude-standard"])
        .output()?;
    if !output.status.success() {
        return Err("git ls-files failed".into());
    }
    let text = String::from_utf8(output.stdout)?;
    Ok(text.lines().map(str::to_owned).collect())
}

pub(super) fn census(root: &Path) -> Result<Census> {
    let mut census = Census {
        over: BTreeMap::new(),
        tests_over: 0,
        generated_over: 0,
    };
    for path in files(root)? {
        let extension = path.rsplit('.').next().unwrap_or_default();
        if !EXTENSIONS.contains(&extension) {
            continue;
        }
        // Listed by the index but deleted from the working tree.
        let Ok(bytes) = std::fs::read(root.join(&path)) else {
            continue;
        };
        let text = String::from_utf8_lossy(&bytes);
        let count = code_lines(&text);
        if count <= LIMIT {
            continue;
        }
        if is_test(&path) {
            census.tests_over += 1;
        } else if is_generated(&path, &text) {
            census.generated_over += 1;
        } else {
            census.over.insert(path, count);
        }
    }
    Ok(census)
}

/// A new offender, a listed file that grew, and an entry the tree no longer needs.
pub(super) fn breaches(
    listed: &BTreeMap<String, usize>,
    over: &BTreeMap<String, usize>,
) -> Vec<String> {
    let mut found = Vec::new();
    for (path, &count) in over {
        match listed.get(path) {
            None => found.push(format!("{path}: {count} lines, over {LIMIT}: split it")),
            Some(&was) if count > was => found.push(format!(
                "{path}: grew from {was} to {count} lines: split it"
            )),
            Some(_) => {}
        }
    }
    for path in listed.keys().filter(|path| !over.contains_key(*path)) {
        found.push(format!(
            "{path}: no longer over {LIMIT}: run `cargo xtask health lines --update`"
        ));
    }
    found
}

/// Entries that appeared or rose since `base`.
fn widened(base: &BTreeMap<String, usize>, now: &BTreeMap<String, usize>) -> Vec<String> {
    let mut found = Vec::new();
    for (path, &count) in now {
        match base.get(path) {
            None => found.push(format!("{TABLE}: {path} was added: the list only shrinks")),
            Some(&was) if count > was => found.push(format!(
                "{TABLE}: {path} rose from {was} to {count}: the list only shrinks"
            )),
            Some(_) => {}
        }
    }
    found
}

/// The list after a tidy: lower counts, fewer entries, and nothing new.
fn tightened(
    listed: &BTreeMap<String, usize>,
    over: &BTreeMap<String, usize>,
) -> BTreeMap<String, usize> {
    let keep = |(path, &was): (&String, &usize)| {
        over.get(path).map(|&count| (path.clone(), count.min(was)))
    };
    listed.iter().filter_map(keep).collect()
}

fn render(files: &BTreeMap<String, usize>) -> String {
    let rows: String = files
        .iter()
        .map(|(path, count)| format!("\"{path}\" = {count}\n"))
        .collect();
    format!("{HEADER}{rows}")
}

/// The gate. `commit`, when given, is the commit whose list this one must stay inside.
pub(crate) fn check(commit: Option<&str>) -> Result<()> {
    let root = std::env::current_dir()?;
    let listed = listed(&root)?;
    let census = census(&root)?;
    let mut errors = breaches(&listed, &census.over);
    if let Some(commit) = commit
        && let Some(old) = file_at(&root, commit, TABLE)?
    {
        errors.extend(widened(&parse(&old)?, &listed));
    }
    if !errors.is_empty() {
        return Err(format!("300-line rule:\n  {}", errors.join("\n  ")).into());
    }
    let shrunk = census
        .over
        .iter()
        .filter(|(path, count)| listed.get(*path).is_some_and(|was| *count < was))
        .count();
    println!(
        "lines: {} listed, none new, none grown{}",
        listed.len(),
        match shrunk {
            0 => String::new(),
            n => format!("; {n} shrank: `cargo xtask health lines --update` locks that in"),
        }
    );
    Ok(())
}

pub(super) fn command(args: &[String]) -> Result<()> {
    if !args.iter().any(|arg| arg == "--update") {
        return check(base(args));
    }
    let root = std::env::current_dir()?;
    let tight = tightened(&listed(&root)?, &census(&root)?.over);
    std::fs::write(root.join(TABLE), render(&tight))?;
    println!("lines: {TABLE} holds {} files", tight.len());
    check(None)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn table(rows: &[(&str, usize)]) -> BTreeMap<String, usize> {
        rows.iter()
            .map(|(path, count)| ((*path).to_owned(), *count))
            .collect()
    }

    /// A git repository holding `files`, one line per count.
    fn repo(files: &[(&str, usize)]) -> tempfile::TempDir {
        let dir = tempfile::tempdir().unwrap();
        for (path, count) in files {
            let path = dir.path().join(path);
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(path, "let a = 1;\n\n".repeat(*count)).unwrap();
        }
        let init = Command::new("git")
            .current_dir(dir.path())
            .args(["init", "-q"])
            .status()
            .unwrap();
        assert!(init.success());
        dir
    }

    #[test]
    fn a_new_301_line_file_fails_and_a_300_line_file_passes() {
        let dir = repo(&[("src/big.rs", 301), ("src/fine.rs", 300)]);
        let census = census(dir.path()).unwrap();
        assert_eq!(census.over, table(&[("src/big.rs", 301)]));
        assert_eq!(
            breaches(&table(&[]), &census.over),
            ["src/big.rs: 301 lines, over 300: split it"]
        );
    }

    #[test]
    fn a_listed_file_that_grows_fails() {
        let dir = repo(&[("src/big.rs", 402)]);
        let over = census(dir.path()).unwrap().over;
        assert_eq!(
            breaches(&table(&[("src/big.rs", 401)]), &over),
            ["src/big.rs: grew from 401 to 402 lines: split it"]
        );
        assert!(breaches(&table(&[("src/big.rs", 402)]), &over).is_empty());
        assert!(breaches(&table(&[("src/big.rs", 500)]), &over).is_empty());
    }

    #[test]
    fn a_listed_file_under_the_limit_must_leave_the_list() {
        let found = breaches(&table(&[("src/split.rs", 400)]), &table(&[]));
        assert_eq!(
            found,
            ["src/split.rs: no longer over 300: run `cargo xtask health lines --update`"]
        );
    }

    #[test]
    fn update_lowers_and_removes_and_never_adds_or_raises() {
        let listed = table(&[("kept", 400), ("gone", 400), ("grown", 350)]);
        let over = table(&[("kept", 390), ("grown", 360), ("new", 500)]);
        assert_eq!(
            tightened(&listed, &over),
            table(&[("kept", 390), ("grown", 350)])
        );
    }

    #[test]
    fn against_the_base_no_entry_appears_or_rises() {
        let base = table(&[("a", 400), ("b", 400)]);
        assert!(widened(&base, &table(&[("a", 390)])).is_empty());
        assert_eq!(
            widened(&base, &table(&[("a", 401), ("c", 301)])),
            [
                "xtask/line-limits.toml: a rose from 400 to 401: the list only shrinks",
                "xtask/line-limits.toml: c was added: the list only shrinks",
            ]
        );
    }

    #[test]
    fn inline_test_modules_do_not_count_and_external_ones_do_not_end_the_count() {
        let inline = "fn a() {}\n\n#[cfg(test)]\nmod tests {\n    fn b() {}\n\n}\nfn c() {}\n";
        assert_eq!(code_lines(inline), 2);
        let external = "#[cfg(test)]\nmod docs;\nfn a() {}\n";
        assert_eq!(code_lines(external), 3);
    }

    #[test]
    fn tests_and_generated_contracts_are_counted_apart() {
        let dir = repo(&[
            ("tests/big.test.ts", 301),
            ("src/repo_store/tests.rs", 301),
            ("src/a_tests.rs", 301),
        ]);
        let contract = dir.path().join("shared/contracts/big.ts");
        std::fs::create_dir_all(contract.parent().unwrap()).unwrap();
        let body = "export type A = 1;\n".repeat(301);
        std::fs::write(&contract, format!("{GENERATED} from x.\n{body}")).unwrap();
        let hand = dir.path().join("shared/contracts/hand.ts");
        std::fs::write(hand, &body).unwrap();
        let census = census(dir.path()).unwrap();
        assert_eq!(census.tests_over, 3);
        assert_eq!(census.generated_over, 1);
        assert_eq!(census.over, table(&[("shared/contracts/hand.ts", 301)]));
    }

    #[test]
    fn the_committed_list_parses_and_round_trips() {
        let source = include_str!("../../line-limits.toml");
        let files = parse(source).unwrap();
        assert!(files.keys().all(|path| !path.contains('"')));
        assert_eq!(render(&files), source);
    }
}
