use super::*;
use serde_json::json;

#[test]
fn the_runtime_crates_are_its_path_dependencies_without_dev_ones() {
    let root = "/w";
    let package = |name: &str, deps: serde_json::Value| json!({"name": name, "manifest_path": format!("{root}/backend/crates/{name}/Cargo.toml"), "dependencies": deps});
    let path = |name: &str| format!("{root}/backend/crates/{name}");
    let metadata = json!({
        "workspace_root": root,
        "packages": [
            package("yoneda-runtime", json!([
                {"name": "yoneda-agents-core", "path": path("yoneda-agents-core"), "kind": null},
                {"name": "serde", "kind": null},
                {"name": "yoneda-app", "path": path("yoneda-app"), "kind": "dev"}
            ])),
            package("yoneda-agents-core", json!([
                {"name": "yoneda-core", "path": path("yoneda-core"), "kind": null}
            ])),
            package("yoneda-core", json!([])),
            package("yoneda-app", json!([])),
            json!({"name": "xtask", "manifest_path": format!("{root}/xtask/Cargo.toml"), "dependencies": []})
        ]
    });
    let crates = runtime_crates(&metadata).unwrap();
    assert_eq!(
        crates,
        [
            "backend/crates/yoneda-agents-core",
            "backend/crates/yoneda-core",
            "backend/crates/yoneda-runtime"
        ]
    );
    let specs = pathspecs(&crates);
    assert!(specs.contains(&"cloudflare/containers".to_owned()));
    assert!(!specs.iter().any(|s| s == "xtask" || s == "Cargo.lock"));
}

const LOCK: &str = r#"# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "serde"
version = "1.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "aa"

[[package]]
name = "sha2"
version = "0.11.0"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "xtask"
version = "0.1.0"
dependencies = [
 "serde 1.0.0",
 "sha2",
 "yoneda-runtime",
]

[[package]]
name = "yoneda-core"
version = "0.1.0"
dependencies = [
 "serde 1.0.0",
]

[[package]]
name = "yoneda-runtime"
version = "0.1.0"
dependencies = [
 "yoneda-core",
]
"#;

#[test]
fn only_the_runtimes_lock_entries_count() {
    let kept = runtime_lock(LOCK).unwrap();
    assert!(kept.contains("name = \"yoneda-runtime\""));
    assert!(kept.contains("name = \"yoneda-core\""));
    assert!(
        kept.contains("checksum = \"aa\""),
        "transitive registry entries count"
    );
    assert!(!kept.contains("xtask") && !kept.contains("sha2"));
    // An xtask-only dependency change leaves the runtime's share unchanged ...
    let xtask_change = LOCK.replace(" \"sha2\",\n", "");
    assert_eq!(runtime_lock(&xtask_change).unwrap(), kept);
    // ... while a runtime dependency change does not.
    let bump = LOCK.replace("checksum = \"aa\"", "checksum = \"bb\"");
    assert_ne!(runtime_lock(&bump).unwrap(), kept);
    assert!(runtime_lock("[[package]]\nname = \"other\"\n").is_err());
}

#[test]
fn the_digest_covers_paths_blobs_and_the_lock() {
    let specs = pathspecs(&["backend/crates/yoneda-runtime".to_owned()]);
    let tree = "100644 blob 0123\tcloudflare/containers/Dockerfile\n";
    let base = digest(&specs, tree, "lock");
    assert_eq!(base.len(), 64);
    assert_eq!(base, digest(&specs, tree, "lock"), "deterministic");
    assert_ne!(base, digest(&specs, &tree.replace("0123", "4567"), "lock"));
    assert_ne!(
        base,
        digest(&specs, &tree.replace("100644", "100755"), "lock")
    );
    assert_ne!(base, digest(&specs, tree, "lock2"));
    assert_ne!(base, digest(&specs[1..], tree, "lock"));
}
