//! `cargo xtask contracts`: writes `shared/contracts/<name>.ts` from the JSON Schemas in
//! `yoneda_platform::shared_contracts`, so the browser's types come from the Rust types that
//! produce the JSON. Each file holds the types and the schema itself. Only the schema
//! subset those types use is rendered; anything else is an error, never a silent `unknown`.
use serde_json::{Map, Value};
use std::path::{Path, PathBuf};

type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;

const DIR: &str = "shared/contracts";

/// Writes every contract under `root` (the workspace).
pub fn write(root: &Path) -> Result<()> {
    std::fs::create_dir_all(root.join(DIR))?;
    for (name, schema) in yoneda_platform::shared_contracts::schemas() {
        std::fs::write(path(root, name), render(name, &schema)?)?;
        println!("wrote {DIR}/{name}.ts");
    }
    Ok(())
}

fn path(root: &Path, name: &str) -> PathBuf {
    root.join(DIR).join(format!("{name}.ts"))
}

/// The TypeScript module for one contract: its root type, its `$defs` in name order, then
/// the schema as a `const`.
fn render(name: &str, schema: &Value) -> Result<String> {
    let title = schema["title"]
        .as_str()
        .ok_or_else(|| format!("{name}: the root schema needs a title"))?;
    let mut out = format!(
        "// Generated by `cargo xtask contracts` from yoneda_platform::shared_contracts. Do not edit.\n\n{}",
        declaration(title, schema)?
    );
    if let Some(defs) = schema["$defs"].as_object() {
        let mut names: Vec<&String> = defs.keys().collect();
        names.sort();
        for def in names {
            out.push('\n');
            out.push_str(&declaration(def, &defs[def])?);
        }
    }
    out.push_str(&format!(
        "\nexport const {}Schema = {} as const;\n",
        camel(name),
        serde_json::to_string_pretty(schema)?
    ));
    Ok(out)
}

fn declaration(name: &str, schema: &Value) -> Result<String> {
    Ok(format!(
        "{}export type {name} = {};\n",
        doc(schema, ""),
        ts(schema, "")?
    ))
}

fn doc(schema: &Value, indent: &str) -> String {
    match schema["description"].as_str() {
        Some(text) => format!(
            "{indent}/** {} */\n",
            text.replace("*/", "* /").replace('\n', " ")
        ),
        None => String::new(),
    }
}

fn camel(name: &str) -> String {
    let mut parts = name.split('-');
    let first = parts.next().unwrap_or_default().to_owned();
    parts.fold(first, |mut out, part| {
        let mut chars = part.chars();
        if let Some(c) = chars.next() {
            out.extend(c.to_uppercase());
            out.push_str(chars.as_str());
        }
        out
    })
}

/// The TypeScript type for `schema`; nested object members are indented past `indent`.
fn ts(schema: &Value, indent: &str) -> Result<String> {
    let Some(map) = schema.as_object() else {
        return match schema {
            Value::Bool(true) => Ok("unknown".into()),
            other => Err(format!("unsupported schema {other}").into()),
        };
    };
    // Annotations alone (a `serde_json::Value` field with a doc comment) allow any value.
    let annotation = |key: &String| matches!(key.as_str(), "description" | "title" | "default");
    if map.keys().all(annotation) {
        return Ok("unknown".into());
    }
    if let Some(target) = map.get("$ref").and_then(Value::as_str) {
        return Ok(target
            .strip_prefix("#/$defs/")
            .ok_or_else(|| format!("unsupported $ref {target}"))?
            .to_owned());
    }
    if let Some(value) = map.get("const") {
        return Ok(value.to_string());
    }
    if let Some(values) = map.get("enum").and_then(Value::as_array) {
        return Ok(values
            .iter()
            .map(Value::to_string)
            .collect::<Vec<_>>()
            .join(" | "));
    }
    for key in ["anyOf", "oneOf"] {
        if let Some(options) = map.get(key).and_then(Value::as_array) {
            let rendered: Result<Vec<String>> = options.iter().map(|o| ts(o, indent)).collect();
            return Ok(rendered?.join(" | "));
        }
    }
    match map.get("type") {
        Some(Value::String(kind)) => typed(kind, map, indent),
        Some(Value::Array(kinds)) => {
            let rendered: Result<Vec<String>> = kinds
                .iter()
                .map(|k| typed(k.as_str().unwrap_or_default(), map, indent))
                .collect();
            Ok(rendered?.join(" | "))
        }
        _ => Err(format!("unsupported schema {schema}").into()),
    }
}

fn typed(kind: &str, map: &Map<String, Value>, indent: &str) -> Result<String> {
    Ok(match kind {
        "string" => "string".into(),
        "integer" | "number" => "number".into(),
        "boolean" => "boolean".into(),
        "null" => "null".into(),
        "array" => {
            let item = ts(map.get("items").unwrap_or(&Value::Bool(true)), indent)?;
            if item.contains(' ') {
                format!("({item})[]")
            } else {
                format!("{item}[]")
            }
        }
        "object" => object(map, indent)?,
        other => return Err(format!("unsupported type {other}").into()),
    })
}

fn object(map: &Map<String, Value>, indent: &str) -> Result<String> {
    let Some(properties) = map.get("properties").and_then(Value::as_object) else {
        let values = match map.get("additionalProperties") {
            None | Some(Value::Bool(true)) => "unknown".into(),
            Some(schema) => ts(schema, indent)?,
        };
        return Ok(format!("Record<string, {values}>"));
    };
    let required: Vec<&str> = map
        .get("required")
        .and_then(Value::as_array)
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let inner = format!("{indent}  ");
    let mut out = String::from("{\n");
    for (key, schema) in properties {
        let optional = if required.contains(&key.as_str()) {
            ""
        } else {
            "?"
        };
        let name = if key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
            key.clone()
        } else {
            Value::String(key.clone()).to_string()
        };
        out.push_str(&doc(schema, &inner));
        out.push_str(&format!(
            "{inner}{name}{optional}: {};\n",
            ts(schema, &inner)?
        ));
    }
    out.push_str(indent);
    out.push('}');
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn root() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .map(Path::to_path_buf)
            .unwrap_or_default()
    }

    #[test]
    fn committed_contracts_match_the_rust_types() {
        for (name, schema) in yoneda_platform::shared_contracts::schemas() {
            let committed = std::fs::read_to_string(path(&root(), name)).unwrap_or_default();
            assert!(
                committed == render(name, &schema).unwrap(),
                "{DIR}/{name}.ts is stale: run `cargo xtask contracts`"
            );
        }
    }

    #[test]
    fn renders_the_schema_subset_and_refuses_the_rest() {
        let schema = serde_json::json!({
            "title": "T", "type": "object", "required": ["a", "kind"],
            "properties": {
                "a": {"type": ["string", "null"], "description": "Doc."},
                "b": {"type": "array", "items": {"anyOf": [{"$ref": "#/$defs/U"}, {"type": "null"}]}},
                "c": {"type": "object", "additionalProperties": {"type": "integer"}},
                "kind": {"const": "x"},
                "e": {"enum": ["p", "q"]},
                "f": true,
            },
        });
        assert_eq!(
            ts(&schema, "").unwrap(),
            "{\n  /** Doc. */\n  a: string | null;\n  b?: (U | null)[];\n  c?: Record<string, number>;\n  e?: \"p\" | \"q\";\n  f?: unknown;\n  kind: \"x\";\n}"
        );
        assert!(ts(&serde_json::json!({"not": {}}), "").is_err());
        assert!(ts(&serde_json::json!({"$ref": "other.json"}), "").is_err());
        assert_eq!(camel("repo-status"), "repoStatus");
    }
}
